export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const CORE_FILES = ['index.html', 'style.css', 'script.js', 'version.json', 'LICENSE', 'NOTICE', 'LICENSES/MIT-original.txt', 'Dockerfile', 'docker-compose.yml', 'nginx.conf', '.gitignore', '.dockerignore', '.gitattributes', 'setup.bat', 'setup.sh', 'README.md', 'CHANGELOG.md', 'DESIGN.md'];
export const CORE_DIRS = ['lib', 'scripts', 'locales', 'assets', 'tests', 'examples'];
export const sha256 = (data) => createHash('sha256').update(data).digest('hex');
export async function exists(file) { try { await lstat(file); return true; } catch (error) { if (error.code === 'ENOENT') return false; throw error; } }
export function localPath(root, relative) {
  if (typeof relative !== 'string' || !relative || relative.includes('\\') || relative.includes(':') || relative.includes('\0') || relative.startsWith('/')) throw new Error('Unsafe relative path.');
  const parts = relative.split('/');
  if (parts.some(part => !part || part === '.' || part === '..' || /[. ]$/.test(part) || /^(con|prn|aux|nul|com[1-9]|lpt[1-9])(?:\.|$)/i.test(part))) throw new Error('Unsafe path segment.');
  const target = path.resolve(root, ...parts);
  if (path.relative(path.resolve(root), target).startsWith('..')) throw new Error('Path escapes project.');
  return target;
}
export async function checkParents(root, relative) {
  const canonicalRoot = await realpath(root); let current = canonicalRoot;
  for (const part of relative.split('/')) {
    current = path.join(current, part);
    if (!await exists(current)) break;
    if ((await lstat(current)).isSymbolicLink()) throw new Error(`Symbolic link is not allowed: ${relative}`);
    const resolved = await realpath(current);
    if (path.relative(canonicalRoot, resolved).startsWith('..')) throw new Error('Path escapes project.');
  }
  return localPath(root, relative);
}
export async function atomicWrite(file, content, mode = 0o600) {
  await mkdir(path.dirname(file), { recursive: true });
  const temporary = `${file}.${randomUUID()}.tmp`;
  try { await writeFile(temporary, content, { flag: 'wx', mode }); await rename(temporary, file); }
  finally { if (await exists(temporary)) await unlink(temporary); }
}
export async function withLock(root, action) {
  const file = path.join(root, '.setup.lock');
  try { await writeFile(file, String(process.pid), { flag: 'wx', mode: 0o600 }); }
  catch (error) {
    if (error.code !== 'EEXIST') throw error;
    if ((await lstat(file)).isSymbolicLink()) throw new Error('Unsafe setup lock.');
    const pid = Number(await readFile(file, 'utf8')); let alive = true;
    if (!Number.isInteger(pid) || pid <= 0) throw new Error('Invalid setup lock; inspect .setup.lock manually.');
    try { process.kill(pid, 0); } catch (failure) { if (failure.code === 'ESRCH') alive = false; }
    if (alive) throw new Error('Another setup/update operation is running (.setup.lock).');
    await unlink(file); await writeFile(file, String(process.pid), { flag: 'wx', mode: 0o600 });
  }
  try { return await action(); } finally { await unlink(file); }
}
export async function loadProfile(root = ROOT) {
  const file = path.join(root, 'user-content/profile.json'); let config;
  if (await exists(file)) {
    await checkParents(root, 'user-content/profile.json');
    config = JSON.parse(await readFile(file, 'utf8'));
    if (Array.isArray(config.pageFiles)) {
      config.pages = [];
      for (const name of config.pageFiles) {
        if (!/^[a-z][a-z0-9-]{0,63}\.json$/.test(name)) throw new Error('Invalid page filename.');
        const pagePath = await checkParents(root, `user-content/pages/${name}`);
        config.pages.push(JSON.parse(await readFile(pagePath, 'utf8')));
      }
    }
  } else if (await exists(path.join(root, 'config.js'))) config = parseLegacyConfig(await readFile(path.join(root, 'config.js'), 'utf8'));
  else config = {};
  const errors = validateConfig(config);
  if (errors.length) throw new Error(errors.join('\n'));
  return normalizeConfig(config);
}
export function profileWrites(input) {
  const config = normalizeConfig(input);
  const writes = new Map();
  const stored = { ...config, pages: [], pageFiles: config.pages.map(page => `${page.id}.json`) };
  for (const page of config.pages) writes.set(`user-content/pages/${page.id}.json`, JSON.stringify(page, null, 2) + '\n');
  writes.set('user-content/profile.json', JSON.stringify(stored, null, 2) + '\n');
  writes.set('config.js', '// Generated by Easy Setup. Personal data; protected from updates.\nwindow.PROFILE_CONFIG = ' + JSON.stringify(config, null, 2) + ';\n');
  return writes;
}
export async function saveProfile(root, input) {
  const errors = validateConfig(input); if (errors.length) throw new Error(errors.join('\n'));
  const config = normalizeConfig(input);
  const writes = profileWrites(config);
  const backup = path.join(root, 'backups', `profile-${Date.now()}-${randomUUID().slice(0, 8)}`);
  const old = new Map();
  for (const [relative] of writes) {
    const target = await checkParents(root, relative);
    old.set(relative, await exists(target) ? await readFile(target) : null);
  }
  if ([...old.values()].some(Boolean)) {
    for (const [relative, content] of old) if (content) {
      const relativeBackup = path.relative(root, path.join(backup, relative)).split(path.sep).join('/');
      await atomicWrite(await checkParents(root, relativeBackup), content);
    }
  }
  try { for (const [relative, content] of writes) await atomicWrite(localPath(root, relative), content); }
  catch (error) {
    for (const [relative, content] of old) {
      const target = localPath(root, relative);
      if (content) await atomicWrite(target, content); else if (await exists(target)) await unlink(target);
    }
    throw error;
  }
  return { config, backup: [...old.values()].some(Boolean) ? backup : null };
}
export async function importMedia(root, source, kind) {
  let name = source.trim();
  if ((name.startsWith('"') && name.endsWith('"')) || (name.startsWith("'") && name.endsWith("'"))) name = name.slice(1, -1);
  if (name.startsWith('~/')) name = path.join(os.homedir(), name.slice(2));
  const info = await stat(name);
  const limit = kind === 'music' ? 30 * 1024 * 1024 : 10 * 1024 * 1024;
  if (!info.isFile() || info.size === 0 || info.size > limit) throw new Error(`Expected a non-empty file smaller than ${limit / 1024 / 1024} MB.`);
  const extension = path.extname(name).toLowerCase(); const bytes = await readFile(name);
  const image = (extension === '.png' && bytes.subarray(0, 8).equals(Buffer.from([137,80,78,71,13,10,26,10])))
    || (['.jpg', '.jpeg'].includes(extension) && bytes[0] === 255 && bytes[1] === 216 && bytes[2] === 255)
    || (extension === '.gif' && /^GIF8[79]a$/.test(bytes.subarray(0, 6).toString()))
    || (extension === '.webp' && bytes.toString('ascii', 0, 4) === 'RIFF' && bytes.toString('ascii', 8, 12) === 'WEBP');
  const audio = (extension === '.mp3' && (bytes.toString('ascii', 0, 3) === 'ID3' || (bytes[0] === 255 && (bytes[1] & 224) === 224)))
    || (extension === '.ogg' && bytes.toString('ascii', 0, 4) === 'OggS')
    || (extension === '.wav' && bytes.toString('ascii', 0, 4) === 'RIFF' && bytes.toString('ascii', 8, 12) === 'WAVE');
  if (!(kind === 'music' ? audio : image)) throw new Error(kind === 'music' ? 'Supported audio: MP3, OGG, WAV; file signature must match.' : 'Supported images: PNG, JPG, GIF, WebP; file signature must match.');
  const relative = `user-content/media/${kind}-${randomUUID()}${extension}`;
  const target = await checkParents(root, relative); await mkdir(path.dirname(target), { recursive: true });
  await copyFile(name, target, constants.COPYFILE_EXCL); await chmod(target, 0o600);
  if (sha256(await readFile(target)) !== sha256(bytes)) throw new Error('Imported file verification failed.');
  return relative;
}
export function mediaReferences(config) {
  const found = new Set();
  const add = value => { if (typeof value === 'string' && value && !/^[a-z]+:/i.test(value) && !value.startsWith('//')) found.add(value.split(/[?#]/)[0]); };
  for (const key of ['avatar', 'cover', 'music']) add(config[key]);
  for (const value of Object.values(config.icons || {})) add(value);
  for (const link of config.links || []) if (!['github', 'tiktok', 'x', 'twitter', 'youtube', 'discord'].includes(link.icon)) add(link.icon);
  for (const page of config.pages) add(page.icon);
  for (const collection of [config.gallery, config.projects, ...config.pages.flatMap(page => [page.images || [], page.projects || []])]) for (const item of collection || []) { add(item.src); add(item.image); }
  return [...found];
}
export async function managedFiles(root = ROOT) {
  const files = [...CORE_FILES];
  async function walk(relative) {
    if (!await exists(path.join(root, relative))) return;
    for (const entry of await readdir(path.join(root, relative), { withFileTypes: true })) {
      const name = `${relative}/${entry.name}`;
      if (entry.isSymbolicLink()) throw new Error(`Symbolic link in source: ${name}`);
      if (entry.isDirectory()) await walk(name); else if (entry.isFile()) files.push(name);
    }
  }
  for (const dir of CORE_DIRS) await walk(dir);
  const result = [];
  for (const file of files) if (await exists(path.join(root, file))) result.push(file);
  return result.sort();
}
export async function buildSite(root = ROOT, destination = path.join(root, 'dist')) {
  const config = await loadProfile(root);
  const relativeDestination = path.relative(root, destination).split(path.sep).join('/');
  await checkParents(root, relativeDestination);
  if (await exists(destination) && !await exists(path.join(destination, '.3ds-build'))) throw new Error('Output directory is not a generated 3DS build; choose an empty directory.');
  const stage = path.join(root, `.build-${randomUUID()}`);
  await mkdir(stage);
  try {
  const files = ['index.html', 'style.css', 'script.js', 'version.json', 'LICENSE', 'NOTICE', 'LICENSES/MIT-original.txt', 'lib/config.mjs', 'lib/releases.mjs', 'lib/content.mjs', 'lib/translations.mjs'];
  for (const dir of ['assets', 'locales']) {
    for (const file of await managedFiles(root)) if (file.startsWith(dir + '/') && !files.includes(file)) files.push(file);
  }
  for (const file of new Set([...files, ...mediaReferences(config)])) {
    const source = await checkParents(root, file); const target = localPath(stage, file);
    await mkdir(path.dirname(target), { recursive: true }); await copyFile(source, target); await chmod(target, 0o644);
  }
  await atomicWrite(path.join(stage, 'config.js'), 'window.PROFILE_CONFIG = ' + JSON.stringify(config) + ';\n', 0o644);
  await atomicWrite(path.join(stage, '.3ds-build'), '1.2.0\n', 0o644);
  let backup;
  if (await exists(destination)) {
    const backupRelative = `backups/build-${Date.now()}-${randomUUID().slice(0, 8)}`;
    backup = await checkParents(root, backupRelative); await mkdir(path.dirname(backup), { recursive: true }); await rename(destination, backup);
  }
  try { await rename(stage, destination); }
  catch (error) { if (backup) await rename(backup, destination); throw error; }
  return destination;
  } finally {
    if (await exists(stage)) {
      const resolved = await realpath(stage); const base = await realpath(root);
      if (path.dirname(resolved) !== base || !path.basename(resolved).startsWith('.build-')) throw new Error('Unsafe build cleanup path.');
      await rm(resolved, { recursive: true });
    }
  }
}
export async function previewSite(root = ROOT, port = 0) {
  const types = { '.html': 'text/html', '.css': 'text/css', '.js': 'text/javascript', '.mjs': 'text/javascript', '.json': 'application/json', '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.gif': 'image/gif', '.webp': 'image/webp', '.mp3': 'audio/mpeg', '.ogg': 'audio/ogg', '.wav': 'audio/wav' };
  const server = createServer(async (request, response) => {
    try {
      if (!['GET', 'HEAD'].includes(request.method)) { response.writeHead(405); return response.end(); }
      const relative = decodeURIComponent(new URL(request.url, 'http://localhost').pathname).slice(1) || 'index.html';
      if (relative.split('/').some(part => part.startsWith('.')) || /^(backups|scripts|tests|user-content\/pages)\//.test(relative) || relative === 'user-content/profile.json') throw new Error('Private path.');
      const file = await checkParents(root, relative); const content = await readFile(file);
      response.writeHead(200, { 'Content-Type': types[path.extname(file)] || 'text/plain', 'Cache-Control': 'no-store', 'X-Content-Type-Options': 'nosniff' }); response.end(request.method === 'HEAD' ? undefined : content);
    } catch { response.writeHead(404); response.end('Not found'); }
  });
  await new Promise((resolve, reject) => { server.once('error', reject); server.listen(port, '127.0.0.1', resolve); });
  return { server, url: `http://127.0.0.1:${server.address().port}/` };
}
